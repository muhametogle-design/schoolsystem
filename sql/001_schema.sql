-- Chronological schooling-history tree (authoritative provenance chain).
-- `previous_mobility_id` models the tree and prevents double-enrollment.
CREATE TABLE public.student_mobility (
    id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    student_id           uuid NOT NULL REFERENCES public.students(id),
    campus_id            uuid NOT NULL REFERENCES public.campus(id),   -- acting campus
    from_campus_id       uuid REFERENCES public.campus(id),
    to_campus_id         uuid NOT NULL REFERENCES public.campus(id),
    from_enrollment_id   uuid REFERENCES public.enrollments(id),
    to_enrollment_id     uuid REFERENCES public.enrollments(id),
    previous_mobility_id uuid REFERENCES public.student_mobility(id),
    edge_type            mobility_edge NOT NULL DEFAULT 'horizontal_transfer',
    transfer_state       transfer_state NOT NULL DEFAULT 'drafted',
    requested_on         date NOT NULL DEFAULT CURRENT_DATE,
    effective_on         date,
    notes                text,
    signed_manifest      bytea,                  -- dean-signed transfer clearance junction
    created_at           timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.transfer_clearances (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    mobility_id      uuid NOT NULL REFERENCES public.student_mobility(id),
    campus_id        uuid NOT NULL REFERENCES public.campus(id),
    clearance_type   text NOT NULL CHECK (clearance_type IN ('academic','financial','disciplinary','hostel','library')),
    issued_by        uuid NOT NULL REFERENCES public.managers(id),
    clearance_state  text NOT NULL CHECK (clearance_state IN ('pending','issued','void')),
    signed_document  bytea NOT NULL,
    issued_at        timestamptz NOT NULL DEFAULT now()
);

