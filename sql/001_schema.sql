-- ---------------------------------------------------------------------------
-- RLS / tenancy helper functions
-- ---------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS app;
CREATE SCHEMA IF NOT EXISTS central;

CREATE OR REPLACE FUNCTION app.current_campus_id() RETURNS uuid AS $$
  SELECT NULLIF(current_setting('neemis.campus_id', true), '')::uuid;
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION app.current_role() RETURNS text AS $$
  SELECT COALESCE(NULLIF(current_setting('neemis.role', true), ''), 'anonymous');
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION app.is_state_role() RETURNS boolean AS $$
  SELECT app.current_role() IN ('state_admin', 'system', 'aggregator');
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION app.assert_campus_match() RETURNS trigger AS $$
BEGIN
  IF NEW.campus_id IS DISTINCT FROM app.current_campus_id()
     AND NOT app.is_state_role() THEN
    RAISE EXCEPTION 'neemis.campus_mismatch: row campus_id % does not match session %',
      NEW.campus_id, app.current_campus_id();
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger body manually added to tenant tables that need campus assertion.

-- Immutable public identifier generators -----------------------------------
CREATE OR REPLACE FUNCTION app.gen_ne_sid() RETURNS trigger AS $$
BEGIN
  IF NEW.id IS NULL THEN NEW.id := gen_random_uuid(); END IF;
  NEW.ne_sid := 'NE-SID-' || replace(new.id::text, '-', '');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION app.gen_ne_tid() RETURNS trigger AS $$
BEGIN
  IF NEW.id IS NULL THEN NEW.id := gen_random_uuid(); END IF;
  NEW.ne_tid := 'NE-TID-' || replace(new.id::text, '-', '');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION app.gen_ne_mid() RETURNS trigger AS $$
BEGIN
  IF NEW.id IS NULL THEN NEW.id := gen_random_uuid(); END IF;
  NEW.ne_mid := 'NE-MID-' || replace(new.id::text, '-', '');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION app.gen_ne_cid() RETURNS trigger AS $$
BEGIN
  IF NEW.id IS NULL THEN NEW.id := gen_random_uuid(); END IF;
  NEW.ne_cid := 'NE-CID-' || upper(new.state_code) || '-' || upper(new.section_code) || '-' || replace(new.id::text, '-', '');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- 1. CAMPUS TENANT
-- ---------------------------------------------------------------------------
CREATE TABLE public.campus (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    campus_code     citext UNIQUE NOT NULL,
    campus_type     campus_type NOT NULL,
    name            text NOT NULL,
    state_code      char(2)  NOT NULL,
    region          text NOT NULL,
    lga             text,
    postal_address  text,
    geo_lat         numeric(10,7),
    geo_lng         numeric(10,7),
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_campus_coords CHECK (
        (geo_lat IS NULL OR geo_lat BETWEEN -90 AND 90) AND
        (geo_lng IS NULL OR geo_lng BETWEEN -180 AND 180)
    )
);

-- ---------------------------------------------------------------------------
-- 2. IDENTITY & ACCESS (globally keyed managers / users)
-- ---------------------------------------------------------------------------
CREATE TABLE public.app_users (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    username        citext UNIQUE NOT NULL,
    email           citext UNIQUE,
    role            text NOT NULL CHECK (role IN ('clerk','dean','state_admin','system','aggregator')),
    campus_id       uuid REFERENCES public.campus(id),
    password_hash   text NOT NULL,
    is_active       boolean NOT NULL DEFAULT true,
    last_login_at   timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

-- NE-MID: global manager identity. Cryptographic verification keys live here.
CREATE TABLE public.managers (
    id                      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    ne_mid                  text UNIQUE NOT NULL,
    user_id                 uuid NOT NULL UNIQUE REFERENCES public.app_users(id),
    campus_id               uuid NOT NULL REFERENCES public.campus(id),
    full_name               text NOT NULL,
    designation             text NOT NULL,          -- principal, dean, bursar, state_director ...
    is_account_holder       boolean NOT NULL DEFAULT false,
    verification_public_key bytea,                  -- Ed25519 SPKI
    signature_scheme        signature_scheme NOT NULL DEFAULT 'ed25519',
    key_version             int NOT NULL DEFAULT 1,
    key_activated_at        timestamptz,
    key_revoked_at          timestamptz,
    is_active               boolean NOT NULL DEFAULT true,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);

CREATE TRIGGER trg_managers_gen_mid BEFORE INSERT ON public.managers
  FOR EACH ROW EXECUTE FUNCTION app.gen_ne_mid();

