-- ============================================================================
-- NE-EMIS — National Education Management Information System
-- PostgreSQL 15+ schema
--
-- Design goals
--   * Multi-tenant (campus-isolated) read/write with centralized state
--     aggregation.
--   * Persistent global identifiers:
--       NE-SID  -> students.id / students.ne_sid
--       NE-TID  -> teachers.id / teachers.ne_tid
--       NE-MID  -> managers.id / managers.ne_mid
--       NE-CID  -> course_sections.id / course_sections.ne_cid
--   * Campus-level Row-Level Security (RLS) so campus clerks/deans only see
--     and write their own campus; the state role reads the global registry.
--   * Cryptographic record locking: dean Ed25519 signatures are stored in
--     record_locks and database triggers freeze the payload rows.
--   * Immutable core identifiers: every identifier column is generated by a
--     BEFORE INSERT trigger and is never updated.
--
-- Execute as a superuser / owner:
--   psql -v ON_ERROR_STOP=1 -f sql/001_schema.sql
-- ============================================================================

BEGIN;

-- gen_random_uuid() is built into PostgreSQL 13+; citext is the only
-- contributed extension the schema requires. Keep it minimal so the schema
-- runs on the official postgres image without extra contrib packages.
CREATE EXTENSION IF NOT EXISTS citext;     -- case-insensitive codes

