-- 7. CRYPTOGRAPHIC RECORD LOCKING (Phase 2)
-- ---------------------------------------------------------------------------
CREATE TABLE public.record_locks (
    id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    campus_id              uuid NOT NULL REFERENCES public.campus(id),
    entity_type            lock_entity NOT NULL,
    entity_id              uuid NOT NULL,
    payload_hash           text NOT NULL,             -- SHA-256 canonical digest
    canonical_payload      jsonb NOT NULL,            -- frozen canonical snapshot
    signature              bytea NOT NULL,            -- Ed25519 signature by dean
    signature_scheme       signature_scheme NOT NULL DEFAULT 'ed25519',
    key_version            int NOT NULL DEFAULT 1,
    locked_by              uuid NOT NULL REFERENCES public.managers(id),
    locked_at              timestamptz NOT NULL DEFAULT now(),
    unlocked_by            uuid REFERENCES public.managers(id),
    unlocked_at            timestamptz,
    unlock_signature       bytea,                     -- state-admin / system counter-signature
    superseded_by          uuid REFERENCES public.record_locks(id),
    UNIQUE (entity_type, entity_id)
);

-- Freeze a row: once locked, ordinary UPDATE/DELETE raises.
CREATE OR REPLACE FUNCTION app.enforce_record_lock() RETURNS trigger AS $$
DECLARE
  lock_row record;
  row_id uuid;
BEGIN
  IF TG_OP = 'DELETE' THEN
    row_id := OLD.id;
  ELSE
    row_id := NEW.id;
  END IF;

  SELECT * INTO lock_row
    FROM public.record_locks
   WHERE entity_type = TG_ARGV[0]::public.lock_entity
     AND entity_id = row_id
     AND unlocked_at IS NULL;

  IF lock_row.id IS NOT NULL AND TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'neemis.record_locked: % is frozen by manager %, payload_hash %',
      TG_ARGV[0], lock_row.locked_by, lock_row.payload_hash
      USING ERRCODE = '55000',
            DETAIL = format('locked_at=%s payload_hash=%s', lock_row.locked_at, lock_row.payload_hash);
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Attach freeze triggers to the lockable Phase-1/2 entities.
CREATE TRIGGER trg_attendance_freeze BEFORE UPDATE OR DELETE ON public.attendance
